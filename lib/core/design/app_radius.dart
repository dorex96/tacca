/// Raggi di arrotondamento dell'app.
///
/// Quattro valori, con un ruolo preciso ciascuno: più ne esistono, più
/// l'interfaccia sembra assemblata a caso.
abstract final class AppRadius {
  /// 8 — tag e badge compatti.
  static const double sm = 8;

  /// 12 — campi di input, pulsanti, menu.
  static const double md = 12;

  /// 16 — card e contenitori.
  static const double lg = 16;

  /// 28 — dialog e bottom sheet (superfici che coprono la pagina).
  static const double xl = 28;
}
